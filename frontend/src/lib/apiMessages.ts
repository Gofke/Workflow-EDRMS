/** The Dutch text for a server message. Messages that are already Dutch pass unchanged. */
export function dutchMessage(status: number, message: string): string {
  const exact = EXACT[message];
  if (exact) return exact;
  for (const [pattern, replacement] of PATTERNS) {
    const m = pattern.exec(message);
    if (m) return typeof replacement === 'string' ? message.replace(pattern, replacement) : replacement(...m.slice(1));
  }
  if (looksDutch(message)) return message;
  if (status >= 500) return 'Er ging iets mis op de server. Probeer het opnieuw; blijft het misgaan, meld het dan aan de beheerder.';
  return BY_STATUS[status] ?? 'Dit is niet gelukt. Probeer het opnieuw.';
}

function looksDutch(text: string): boolean {
  return /\b(de|het|een|niet|van|voor|u|uw|is|zijn|met)\b/i.test(text) && !/\b(the|is not|must|cannot|please|your)\b/i.test(text);
}
